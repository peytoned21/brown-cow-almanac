"""Render a league's site shell from the shared template and its league config.

Usage: python3 pipeline/page.py LEAGUE_CONFIG [TEMPLATE]
Writes <site.dir>/index.html, <site.dir>/manifest.webmanifest and <site.dir>/sw.js. Only the masthead, title, art,
colors, page notes and publishing details come from the config; the page itself is the same for every league and
reads its numbers from data.json.
"""
import hashlib, html, json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
cfg = json.load(open(sys.argv[1]))
tpl = open(sys.argv[2] if len(sys.argv) > 2 else os.path.join(ROOT, 'pipeline', 'template.html')).read()
P = cfg['page']; SITE = cfg['site']
OUT = os.path.join(ROOT, SITE['dir'])
e = lambda s: html.escape(s, quote=False).replace('"', '&quot;')  # double-quoted attributes only

art = P.get('art') or {}
emblem = (f'      <a class="emblem" href="#home" aria-label="{e(P["brandAria"])}"><img src="{e(art["emblem"])}" alt=""></a>\n'
          if art.get('emblem') else '')
framed = (f'      <figure class="framed"><div class="mat"><div class="gold"><img src="{e(art["painting"])}" alt="{e(art["alt"])}" '
          f'width="{art["width"]}" height="{art["height"]}"></div></div><figcaption>{e(art["caption"])}</figcaption></figure>\n'
          if art.get('painting') else '')
h1 = f'<span class="cow">{e(P["h1Main"])}</span>' + (f' <span class="ver">{e(P["h1Ver"])}</span>' if P.get('h1Ver') else '')
css = f'<style>\n{P["css"].strip()}\n</style>' if P.get('css', '').strip() else ''
icon = SITE['icon']
head = (f'<meta name="robots" content="noindex,nofollow"><meta name="theme-color" content="{SITE["theme"]}">'
        f'<link rel="manifest" href="manifest.webmanifest"><link rel="icon" href="{icon}-192.png">'
        f'<link rel="apple-touch-icon" href="{os.path.dirname(icon)}/apple-touch-icon.png">'
        f'<meta name="apple-mobile-web-app-capable" content="yes"><meta name="mobile-web-app-capable" content="yes">'
        f'<meta name="apple-mobile-web-app-status-bar-style" content="black-translucent"><meta name="apple-mobile-web-app-title" content="{e(SITE["short"])}">')

cut = cfg.get('cutoffs', {})
lg = dict(
    copyPrefix=P['copyPrefix'], notes=P['notes'], me=cfg.get('me'),
    bridesmaid=(cfg.get('oneOffs') or {}).get('bridesmaid'),
    seedsFrom=cut.get('seedsFrom', 0), earlyWeeks=cut.get('earlyWeeks', 6), losersLadder=bool(cfg.get('losersLadder')),
    tiebreak=cfg.get('seedTiebreak', 'h2h'), nColors=P.get('nColors', 12),
    site=SITE['url'], liveUrl=SITE['liveUrl'], slug=SITE['slug'], paper=P.get('paperName', 'The Weekly'),
)
# </script> can't appear inside the inline script
lg_json = json.dumps(lg, ensure_ascii=False, separators=(',', ':')).replace('</', '<\\/')

out = tpl
for k, v in {'{{title}}': e(P['title']), '{{HEAD}}': head, '{{EMBLEM}}': emblem, '{{eyebrow}}': e(P['eyebrow']), '{{H1}}': h1,
             '{{tagline}}': e(P['tagline']), '{{FRAMED}}': framed, '{{plateTitle}}': e(P['plateTitle']),
             '{{loading}}': e(P['loading']), '{{CSS}}': css, '{{LG_JSON}}': lg_json}.items():
    assert out.count(k) == 1, k
    out = out.replace(k, v)
assert '{{' not in out

# keep the link-preview tags that cards.py wrote into the previous build
ip = os.path.join(OUT, 'index.html')
if os.path.exists(ip):
    old = open(ip).read(); a, b = old.find('<!--og-->'), old.find('<!--/og-->')
    if a != -1 and b != -1:
        out = out.replace('<meta name="robots"', old[a:b + len('<!--/og-->')] + '<meta name="robots"', 1)
os.makedirs(OUT, exist_ok=True)
open(ip, 'w').write(out)

manifest = dict(name=P['title'], short_name=SITE['short'], start_url='./', scope='./', display='standalone',
                background_color=SITE['bg'], theme_color=SITE['theme'], description=P['tagline'],
                icons=[dict(src=f'{icon}-192.png', sizes='192x192', type='image/png'),
                       dict(src=f'{icon}-512.png', sizes='512x512', type='image/png'),
                       dict(src=f'{os.path.dirname(icon)}/icon-maskable-512.png', sizes='512x512', type='image/png', purpose='maskable')])
json.dump(manifest, open(os.path.join(OUT, 'manifest.webmanifest'), 'w'), indent=2, ensure_ascii=False)

# service worker: the page shell and data are network-first with an offline fallback; live feeds are never cached
others = [json.load(open(os.path.join(ROOT, 'leagues', f)))['site']['dir'] for f in sorted(os.listdir(os.path.join(ROOT, 'leagues')))]
skip = [d for d in others if d and d != SITE['dir']]
pre = ['./', 'index.html', 'data.json', 'manifest.webmanifest', f'{icon}-192.png', f'{icon}-512.png'] + \
      ([art['emblem']] if art.get('emblem') else []) + ([art['painting']] if art.get('painting') else [])
ver = hashlib.sha1((out + json.dumps(pre)).encode()).hexdigest()[:10]
sw = f"""/* {P['title']}: offline cache. Generated by pipeline/page.py. */
const V = 'almanac-{SITE['slug']}-{ver}';
const PRE = {json.dumps(pre)};
const SKIP = {json.dumps(['/' + d + '/' for d in skip])};  // other leagues' folders have their own worker
self.addEventListener('install', (e) => {{ e.waitUntil(caches.open(V).then((c) => c.addAll(PRE)).then(() => self.skipWaiting())); }});
self.addEventListener('activate', (e) => {{ e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k.startsWith('almanac-{SITE['slug']}-') && k !== V).map((k) => caches.delete(k)))).then(() => self.clients.claim())); }});
self.addEventListener('fetch', (e) => {{
  const r = e.request; if (r.method !== 'GET') return;
  const u = new URL(r.url);
  const fonts = /fonts\\.(googleapis|gstatic)\\.com$/.test(u.hostname);
  if (u.origin !== location.origin && !fonts) return;          // ESPN, live feeds: always the network
  if (SKIP.some((p) => u.pathname.includes(p))) return;
  if (/live\\.json$/.test(u.pathname)) return;
  if (fonts) {{ e.respondWith(caches.open(V).then((c) => c.match(r).then((hit) => hit || fetch(r).then((res) => {{ c.put(r, res.clone()); return res; }})))); return; }}
  // network first, so the stats are fresh whenever there's signal; cached copy when there isn't
  e.respondWith(fetch(r).then((res) => {{ if (res.ok) {{ const cp = res.clone(); caches.open(V).then((c) => c.put(r, cp)); }} return res; }})
    .catch(() => caches.open(V).then((c) => c.match(r, {{ ignoreSearch: true }}).then((hit) => hit || (r.mode === 'navigate' ? c.match('index.html') : undefined)))));
}});
"""
open(os.path.join(OUT, 'sw.js'), 'w').write(sw)
print('wrote', os.path.relpath(ip, ROOT), '+ manifest + sw.js')
